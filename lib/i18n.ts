export type Locale = "cs" | "en";

export const locales: Locale[] = ["cs", "en"];

/** Prefix interních odkazů podle jazyka: cs = bez prefixu, en = /en. */
export function localePath(locale: Locale, path: string): string {
  return locale === "en" ? `/en${path === "/" ? "" : path}` || "/en" : path;
}

/**
 * Číslo s pevnou mezerou po tisících („1 007“). Schválně bez Intl:
 * server i klient musí vyrobit tentýž řetězec, jinak React hlásí hydration mismatch.
 */
export function formatCount(n: number): string {
  return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, " ");
}

